/** Направление сортировки списка. */
export const enum SortDirection {
  /** None: без сортировки, исходный порядок элементов. */
  None = 0,
  /** Asc: по возрастанию. */
  Asc = 1,
  /** Desc: по убыванию. */
  Desc = 2,
}

export const enum TextCase {
  /** Первое слово с большой буквы. */
  Capitalize = 0,
  /** Текст без изменения регистра. */
  AsIs = 1,
  /** Весь текст заглавными буквами. */
  Uppercase = 2,
}
